/**
 * Calculate configuration statistics
 */
export const calculateStatistics = (params: ConfigParam[]): ConfigStatistics => {
  return {
    totalParams: params.length,
    changed: params.filter(p => p.value !== p.defaultValue).length,
    requiresRestart: params.filter(p => p.requiresRestart && p.value !== p.defaultValue).length,
  };
};

/**
 * Get unique categories from config parameters
 */
export const getCategories = (params: ConfigParam[]): string[] => {
  return Array.from(new Set(params.map(p => p.category)));
};

/**
 * Filter parameters by category
 */
export const getParamsByCategory = (params: ConfigParam[], category: string): ConfigParam[] => {
  return params.filter(p => p.category === category);
};

/**
 * Generate postgresql.conf file content
 */
export const generateConfigFile = (params: ConfigParam[]): string => {
  const groupedByCategory: Record<string, ConfigParam[]> = {};
  
  params.forEach(param => {
    if (!groupedByCategory[param.category]) {
      groupedByCategory[param.category] = [];
    }
    groupedByCategory[param.category].push(param);
  });

  let config = `# PostgreSQL Configuration File
# Generated by PostgreSQL DBMS Admin Panel
# Date: ${new Date().toISOString().split('T')[0]}
`;

  const categoryHeaders: Record<string, string> = {
    memory: 'MEMORY SETTINGS',
    connections: 'CONNECTION SETTINGS',
    wal: 'WRITE-AHEAD LOG (WAL)',
    autovacuum: 'AUTOVACUUM',
    logging: 'LOGGING',
    performance: 'QUERY TUNING / PERFORMANCE',
  };

  Object.entries(groupedByCategory).forEach(([category, categoryParams]) => {
    config += `
#------------------------------------------------------------------------------
# ${categoryHeaders[category] || category.toUpperCase()}
#------------------------------------------------------------------------------
`;
    categoryParams.forEach(param => {
      config += `${param.name} = ${param.value}\n`;
    });
  });

  return config;
};

/**
 * Export configuration as JSON
 */
export const exportConfigAsJSON = (params: ConfigParam[], profileName: string = 'config'): void => {
  const config = {
    name: profileName,
    generatedAt: new Date().toISOString(),
    parameters: params.reduce((acc, param) => {
      acc[param.name] = param.value;
      return acc;
    }, {} as Record<string, string>),
  };

  const blob = new Blob([JSON.stringify(config, null, 2)], {
    type: 'application/json',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `postgresql-config-${Date.now()}.json`;
  link.click();
  URL.revokeObjectURL(url);
};

/**
 * Export configuration as .conf file
 */
export const exportConfigAsFile = (params: ConfigParam[]): void => {
  const content = generateConfigFile(params);
  
  const blob = new Blob([content], {
    type: 'text/plain',
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `postgresql-${Date.now()}.conf`;
  link.click();
  URL.revokeObjectURL(url);
};

/**
 * Validate configuration parameter value
 */
export const validateParamValue = (param: ConfigParam, value: string): {
  valid: boolean;
  error?: string;
} => {
  // Basic validation - can be extended
  if (!value || value.trim() === '') {
    return { valid: false, error: 'Значення не може бути порожнім' };
  }

  // Validate numeric values
  if (param.unit && !value.match(/^\d+[A-Za-z]*$/)) {
    return { valid: false, error: 'Неправильний формат значення' };
  }

  // Validate boolean values
  if (['on', 'off'].includes(param.defaultValue)) {
    if (!['on', 'off'].includes(value)) {
      return { valid: false, error: 'Значення має бути "on" або "off"' };
    }
  }

  return { valid: true };
};

/**
 * Parse .conf file content
 */
export const parseConfigFile = (content: string): Record<string, string> => {
  const config: Record<string, string> = {};
  const lines = content.split('\n');

  lines.forEach(line => {
    // Skip comments and empty lines
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;

    // Parse parameter = value
    const match = trimmed.match(/^([a-z_]+)\s*=\s*(.+)$/);
    if (match) {
      const [, key, value] = match;
      config[key] = value.trim();
    }
  });

  return config;
};

/**
 * Check if parameter has been modified
 */
export const isParamModified = (param: ConfigParam): boolean => {
  return param.value !== param.defaultValue;
};


/**
 * Compare two configurations
 */
export const compareConfigs = (
  config1: Record<string, string>,
  config2: Record<string, string>
): {
  same: string[];
  different: string[];
  onlyInFirst: string[];
  onlyInSecond: string[];
} => {
  const allKeys = new Set([...Object.keys(config1), ...Object.keys(config2)]);
  const result = {
    same: [] as string[],
    different: [] as string[],
    onlyInFirst: [] as string[],
    onlyInSecond: [] as string[],
  };

  allKeys.forEach(key => {
    if (config1[key] && config2[key]) {
      if (config1[key] === config2[key]) {
        result.same.push(key);
      } else {
        result.different.push(key);
      }
    } else if (config1[key]) {
      result.onlyInFirst.push(key);
    } else {
      result.onlyInSecond.push(key);
    }
  });

  return result;
};

/**
 * Format file size for display
 */
export const formatFileSize = (bytes: number): string => {
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  let size = bytes;
  let unitIndex = 0;

  while (size >= 1024 && unitIndex < units.length - 1) {
    size /= 1024;
    unitIndex++;
  }

  return `${size.toFixed(2)} ${units[unitIndex]}`;
};

/**
 * Estimate memory usage from configuration
 */
export const estimateMemoryUsage = (params: ConfigParam[]): number => {
  let totalMB = 0;

  params.forEach(param => {
    if (param.category === 'memory' && param.unit) {
      const value = parseFloat(param.value);
      if (param.unit === 'GB') {
        totalMB += value * 1024;
      } else if (param.unit === 'MB') {
        totalMB += value;
      }
    }
  });

  return totalMB;
};
